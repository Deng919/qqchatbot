const fs=require('fs'),vm=require('vm'),assert=require('node:assert/strict');
const path=require('path').join(__dirname,'../qq_digest/web/templates/group_selector.html');
assert.ok(fs.existsSync(path),'shared group selector must exist');
const code=fs.readFileSync(path,'utf8').match(/<script>([\s\S]*?)<\/script>/)[1];
const context={URLSearchParams,console};vm.createContext(context);vm.runInContext(code,context);
const selector=context.GroupSelector;
const scope=selector.createState({allowAll:true,selected:[1,3]});
scope.setGroups([{group_id:1,name:'一群'},{group_id:2,name:'二群'},{group_id:3,name:'三群'}]);
scope.chooseVisible('二',true);
assert.equal(scope.ids().join(','),'1,3,2','filter selection preserves hidden chosen groups');
scope.chooseVisible('二',false);assert.equal(scope.ids().join(','),'1,3');
scope.setGroups([{group_id:1,name:'一群'}]);assert.equal(scope.ids().join(','),'1,3','missing saved groups must not widen selection');
scope.clear();assert.throws(()=>scope.value(),/选择/,'specified empty must not mean all');
scope.setAll();assert.equal(scope.value(),null);
scope.setSelected([3,1,3]);assert.equal(scope.ids().join(','),'3,1');
const p=new URLSearchParams({group_id:'9',page:'2'});selector.appendParams(p,scope.value());
assert.equal(p.has('group_id'),false);assert.equal(p.getAll('group_ids').join(','),'3,1');
selector.appendParams(p,null);assert.equal(p.has('group_ids'),false);
assert.throws(()=>selector.parseValue('__empty__'),/选择/);
assert.equal(selector.parseValue('1,3').join(','),'1,3');
assert.throws(()=>selector.createState({allowAll:false}).value(),/选择/);
console.log('Group selection preserves scope, filtering and empty/all distinction');
