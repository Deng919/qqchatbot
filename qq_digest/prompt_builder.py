# ── 段落 5：通用约束（固定） ──────────────────────────────────────

CONSTRAINTS_PROMPT = """\
通用约束：
1. 只基于输入消息生成摘要，不得编造、补充或推断未提及的内容。
2. 摘要用客观第三人称描述，不使用"我""我们""大家"。
3. 结论用已完成时态，任务用将来时态。
4. 如果消息完全是闲聊或系统通知，overview 使用一句客观说明，main_topics 可以为空数组，但 group_id 必须始终返回。
5. 候选筛选标准不变，不要因为数据少就放宽标准。当天无符合标准的候选时，candidates 返回空数组。
6. 如果消息被截断，摘要只覆盖实际收到的消息，在对应话题 summary 末尾标注"[上下文不完整]"。
7. 只输出 JSON，不输出 Markdown 代码块或额外文字。"""

