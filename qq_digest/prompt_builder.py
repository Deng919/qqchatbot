def build_system_prompt(category: str) -> str:
    """组装单一的分类感知自适应摘要 prompt。"""
    sections = [
        ROLE_PROMPT,
        FORMAT_ADAPTIVE,
        _STRATEGY_MAP.get(category, STRATEGY_GENERAL),
        ADAPTIVE_COVERAGE,
        _CANDIDATE_MAP.get(category, CANDIDATE_GENERAL) + "\n\n" + CANDIDATE_COMMON,
        CONSTRAINTS_PROMPT,
    ]
    return "\n\n".join(sections)


def build_user_prompt(
    *,
    group_id: int,
    group_name: str,
    category: str,
    report_date: str,
    window_start: str,
    window_end: str,
    message_count: int,
    source_message_count: int,
    discarded_message_count: int,
    context: str,
    deterministic: dict[str, list[str]],
    keywords: list[str] | None = None,
    knowledge_base: str = "",
    context_truncated: bool = False,
) -> str:
    """按 prompt-template.md 格式组装 user prompt。"""
    kb = knowledge_base.strip() if knowledge_base.strip() else "（空）"
    keyword_text = "、".join(keywords or []) or "（未配置）"
    quality = "上下文已截断，只能总结下方实际提供的消息。" if context_truncated else "上下文完整。"
    return (
        f"群ID: {group_id}\n"
        f"群名: {group_name}\n"
        f"群分类: {category}\n"
        f"群重点关键词: {keyword_text}\n"
        "关键词仅用于优先关注相关讨论，不得因为命中关键词而降低候选标准。\n"
        f"日期: {report_date}\n"
        f"时间窗: {window_start} 到 {window_end}\n"
        f"消息数量: {message_count}\n"
        f"原始 {source_message_count} 条，清洗丢弃 {discarded_message_count} 条，实际纳入 {message_count} 条。\n"
        f"数据质量: {quality}\n"
        f"确定性提取: {deterministic}\n\n"
        f"已有知识库内容（用于去重）：\n{kb}\n\n"
        f"今日消息（{message_count} 条）：\n{context}"
    )
